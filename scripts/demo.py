"""Demo kit: run 3 fixed examples through the real pipeline (local Ollama qwen2.5:7b).

Each example runs twice: the first pass warms the SQLite cache, and the second pass shows cached speed.

Usage:
    LLM_PROVIDER=ollama LLM_MODEL=qwen2.5:7b python scripts/demo.py
    LLM_PROVIDER=ollama LLM_MODEL=qwen2.5:7b python scripts/demo.py --markdown EVIDENCE/demo_expected_output.md
"""

import argparse
import os
import sys
import time
from pathlib import Path

os.environ.setdefault("LLM_PROVIDER", "ollama")
os.environ.setdefault("LLM_MODEL", "qwen2.5:7b")

root_dir = Path(__file__).resolve().parent.parent
if str(root_dir) not in sys.path:
    sys.path.insert(0, str(root_dir))

from backend.config import get_active_model, get_active_provider
from backend.evaluation.pipeline import evaluate

EXAMPLES = [
    {
        "name": "1. All-correct answer",
        "question": "What is the capital of France and when was the Eiffel Tower completed?",
        "answer": "Paris is the capital of France. The Eiffel Tower in Paris was completed in 1889.",
        "expect": "every claim Supported",
    },
    {
        "name": "2. One planted error",
        "question": "Who wrote Romeo and Juliet?",
        "answer": "William Shakespeare wrote Romeo and Juliet. Shakespeare was born in 1564 in Paris, France.",
        "expect": "authorship and birth year Supported; 'born in Paris' Contradicted (he was born in Stratford-upon-Avon)",
    },
    {
        "name": "3. Fabricated entity",
        "question": "What is Dr. Velmora Quistan known for?",
        "answer": "Dr. Velmora Quistan is a Lithuanian physicist who invented the zero-gravity battery at the Kaunas Institute of Quantum Storage in 2017.",
        "expect": "claims Unsupported (no evidence the person or institute exists)",
    },
]


def run_once(ex: dict) -> tuple[dict, float]:
    t0 = time.time()
    result = evaluate(question=ex["question"], answer=ex["answer"], retrieval=True)
    return result, time.time() - t0


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--markdown", default=None, help="Also write the outputs as markdown to this file")
    args = ap.parse_args()

    lines = [
        "# Demo: expected output",
        "",
        f"Provider `{get_active_provider()}`, model `{get_active_model()}`, retrieval ON. "
        "Generated by `scripts/demo.py`. Verdicts can change if the live web results change; "
        "after the first run the SQLite cache replays them exactly.",
        "",
    ]
    print(f"Provider: {get_active_provider()} | Model: {get_active_model()}")
    for ex in EXAMPLES:
        first, t_first = run_once(ex)
        second, t_second = run_once(ex)
        s = second["summary"]
        same = [c["status"] for c in first["claims"]] == [c["status"] for c in second["claims"]]
        print("\n" + "=" * 78)
        print(ex["name"])
        print(f"Q: {ex['question']}\nA: {ex['answer']}")
        print(f"Expected: {ex['expect']}")
        for c in second["claims"]:
            print(f"  [{c['status'].upper():12}] {c['text']}")
            for u in c["sources"]:
                print(f"                 source: {u}")
        print(
            f"F={s['factuality_score']} V={s['verifiable_precision']} U={s['unverifiable_rate']} | "
            f"LLM calls {second['cost_log']['llm_calls']}, search calls {second['cost_log']['search_calls']}"
        )
        print(f"Time: first run {t_first:.2f}s, cached run {t_second:.2f}s | verdicts identical: {same}")

        lines += [
            f"## {ex['name']}",
            "",
            f"- **Question:** {ex['question']}",
            f"- **Answer:** {ex['answer']}",
            f"- **What we expect:** {ex['expect']}",
            "",
            "| Verdict | Claim | Sources |",
            "|---|---|---|",
        ]
        for c in second["claims"]:
            lines.append(f"| {c['status']} | {c['text']} | {'<br>'.join(c['sources']) or '-'} |")
        lines += [
            "",
            f"- Summary: F = {s['factuality_score']}, V = {s['verifiable_precision']}, U = {s['unverifiable_rate']}. {s['interpretation']}",
            f"- Cost: {second['cost_log']['llm_calls']} LLM calls, {second['cost_log']['search_calls']} search calls",
            f"- Time: first run {t_first:.2f} s, cached rerun {t_second:.2f} s (verdicts identical: {same})",
            "",
        ]
        for c in second["claims"]:
            lines.append(f"  - *{c['text']}*: {c['reasoning']}")
        lines.append("")

    if args.markdown:
        Path(args.markdown).write_text("\n".join(lines), encoding="utf-8")
        print(f"\n[SAVED] {args.markdown}")


if __name__ == "__main__":
    main()
